// Register the shipped font faces with the browser and wait for the ones a
// document uses, so the first frame draws with the same metrics layout used.
//
// Bandwidth: only two files per family are shipped, each a subset of the
// characters PlaySnack renders (snack-player/scripts/subset_fonts.py):
//   body    — Snack Body 500 (Pretendard subset) answers weights ≤ 600,
//             Snack Body 700 answers weights ≥ 650.
//   display — Galmuri11 answers weights ≤ 549, Galmuri11 Bold ≥ 550.
// A weight is drawn with the nearest file at or below it (600 → 500, 800/900 →
// 700), so drawn text is never wider than the metrics layout measured it with
// (Latin advances grow with weight; Hangul advances are equal across weights).
// The untouched originals (*-full.woff2) sit behind each subset as a second
// family and are fetched only when a character outside the subset is drawn
// (ensureGlyphs; the renderer redraws that text once the face is in).
import { faceFor } from "@snack/bite-layout";

export const FAMILY = {
  body: "Bite Body",
  display: "Bite Display",
};
const FULL = {
  body: "Bite Body Full",
  display: "Bite Display Full",
};
const EMOJI_FALLBACK = '"Apple Color Emoji", "Segoe UI Emoji", "Noto Color Emoji", sans-serif';
export const fontFamily = (font) => {
  const f = font === "display" ? "display" : "body";
  return `"${FAMILY[f]}", "${FULL[f]}", ${EMOJI_FALLBACK}`;
};

// One entry per shipped file: which family, which CSS weights it answers.
const FILES = {
  body500: { font: "body", file: "snackbody-500.woff2", full: "pretendard-500-full.woff2", weight: "1 649" },
  body700: { font: "body", file: "snackbody-700.woff2", full: "pretendard-700-full.woff2", weight: "650 1000" },
  display400: { font: "display", file: "galmuri11.woff2", full: "galmuri11-full.woff2", weight: "1 549" },
  display700: { font: "display", file: "galmuri11-bold.woff2", full: "galmuri11-bold-full.woff2", weight: "550 1000" },
};
// What each full face can add beyond its subset (generated by subset_fonts.py).
const FULL_RANGES = {
  // <full-ranges>
  body500: "U+100-21B, U+2B0-303, U+391-451, U+1D43-1DBB, U+1E80-1EF3, U+2002-215F, U+2202-2260, U+24B6-24FF, U+25E6-266A, U+2717-277F, U+2C7C, U+321C, U+AC07-D7A3, U+E131-E162, U+F000-F057, U+FFE6, U+1F130-1F189, U+F0000",
  body700: "U+100-21B, U+2B0-303, U+391-451, U+1D43-1DBB, U+1E80-1EF3, U+2002-215F, U+2202-2260, U+24B6-24FF, U+25E6-266A, U+2717-277F, U+2C7C, U+321C, U+AC07-D7A3, U+E131-E162, U+F000-F057, U+FFE6, U+1F130-1F189, U+F0000",
  display400: "U+100-2DD, U+37E-4F9, U+1E00-1EFF, U+203B-2318, U+2474-28FF, U+2C7B, U+3012-30FE, U+3200-33DD, U+4E00-7E9C, U+7F36-8B9A, U+8C37-9481, U+9577-9FA0, U+AC02-D7A3, U+E000-E0DB, U+F000-F03D, U+F8FF-FA2D, U+FE10-FE48, U+FF5F-FFFD",
  display700: "U+203B-218B, U+2474-28FF, U+301C, U+3200-33DD, U+AC02-D7A3, U+E000-E0DB, U+F000-F007, U+F8FF, U+FE10-FE30, U+FF5F-FFFD",
  // </full-ranges>
};

/** The file that draws a resolved weight (see the header). */
export function fileFor(font, weight) {
  if (font === "display") return weight >= 550 ? "display700" : "display400";
  return weight >= 650 ? "body700" : "body500";
}

const loaded = new Map();
const parsedRanges = new Map(); // file key → [[lo, hi], …]
const fullLoads = new Map(); // file key → Promise (the full face, once asked for)

function rangesOf(key) {
  if (!parsedRanges.has(key)) {
    const list = (FULL_RANGES[key] ?? "").split(",").map((r) => {
      const [lo, hi = lo] = r.trim().slice(2).split("-");
      return [parseInt(lo, 16), parseInt(hi, 16)];
    });
    parsedRanges.set(key, list);
  }
  return parsedRanges.get(key);
}

/** True when `text` has a character the subset lacks (so the full face draws it). */
export function needsFullFace(key, text) {
  const ranges = rangesOf(key);
  for (const ch of text) {
    const cp = ch.codePointAt(0);
    for (const [lo, hi] of ranges) if (cp >= lo && cp <= hi) return true;
  }
  return false;
}

/**
 * Fetch the full face when `text` has glyphs the shipped subset lacks (a rare
 * syllable in a nickname: 뷁, 똠…). Text drawn before it arrives falls back to a
 * system font; the returned promise (one per file, shared) resolves once the
 * face is in, so the caller can redraw. null when the subset already covers it.
 */
export function ensureGlyphs(font, weight, text) {
  const key = fileFor(font, weight);
  if (!loaded.has(key) || !needsFullFace(key, text)) return null;
  if (!fullLoads.has(key)) {
    const f = FILES[key];
    const spec = `${f.weight.split(" ")[0]} 16px "${FULL[f.font]}"`;
    // load(spec, text) fetches only faces whose unicode-range meets `text`.
    fullLoads.set(key, document.fonts.load(spec, text).catch((e) => console.warn(`[bite] full font ${key} failed`, e)));
  }
  return fullLoads.get(key);
}

function filesUsed(doc) {
  const used = new Set();
  const visit = (node) => {
    if (!node || typeof node !== "object") return;
    if ("text" in node) {
      const font = node.font === "display" ? "display" : "body";
      // A templated weight can be anything: load the face for the literal or the default.
      const weight = typeof node.weight === "number" ? node.weight : undefined;
      used.add(fileFor(font, faceFor(font, weight).weight));
    }
    for (const c of node.children ?? []) visit(c);
  };
  visit(doc.view);
  for (const def of Object.values(doc.components ?? {})) visit(def.view);
  return used;
}

/** Load every face the document references. Resolves even if a font fails. */
export async function loadFonts(doc, base = "/fonts") {
  const jobs = [];
  for (const key of filesUsed(doc)) {
    if (!loaded.has(key)) {
      const f = FILES[key];
      const face = new FontFace(FAMILY[f.font], `url(${base}/${f.file}) format("woff2")`, { weight: f.weight });
      document.fonts.add(face);
      loaded.set(key, face.load().catch((e) => console.warn(`[bite] font ${key} failed`, e)));
      // Registered, not loaded: the browser fetches it only for characters
      // the subset lacks (and only those inside its unicode-range).
      const range = FULL_RANGES[key];
      if (range) document.fonts.add(new FontFace(FULL[f.font], `url(${base}/${f.full}) format("woff2")`, { weight: f.weight, unicodeRange: range }));
    }
    jobs.push(loaded.get(key));
  }
  await Promise.all(jobs);
}
