// Generates src/metrics.js — glyph advance widths for the fonts Bite ships,
// so Node (gates) and browsers (players) measure text identically.
//
// One-off tool, not a runtime dependency. Usage:
//   pnpm dlx --package=opentype.js@2.0.0 node tools/gen-metrics.mjs <pretendard-otf-dir> <galmuri-ttf-dir>
// Sources: npm `pretendard@1.3.9` (dist/public/static) and `galmuri@2.40.3` (dist), both SIL OFL 1.1.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const require = createRequire(join(process.cwd(), "noop.js"));
const opentype = require("opentype.js");

const [pretDir, galDir] = process.argv.slice(2);
if (!pretDir || !galDir) {
  console.error("usage: gen-metrics.mjs <pretendard-otf-dir> <galmuri-ttf-dir>");
  process.exit(1);
}

const FACES = {
  body: {
    400: join(pretDir, "Pretendard-Regular.otf"),
    500: join(pretDir, "Pretendard-Medium.otf"),
    600: join(pretDir, "Pretendard-SemiBold.otf"),
    700: join(pretDir, "Pretendard-Bold.otf"),
    800: join(pretDir, "Pretendard-ExtraBold.otf"),
    900: join(pretDir, "Pretendard-Black.otf"),
  },
  display: {
    400: join(galDir, "Galmuri11.ttf"),
    700: join(galDir, "Galmuri11-Bold.ttf"),
  },
};

// Ranges a Korean snack app actually renders: ASCII, Latin-1, punctuation,
// arrows/math/shapes/symbols, enclosed numbers, Korean jamo, CJK punctuation
// and fullwidth forms. Hangul syllables are stored as one width (uniform in
// both faces); emoji come from the system emoji font (see measure.js).
const RANGES = [
  [0x20, 0x7e], [0xa0, 0xff], [0x2010, 0x206f], [0x2100, 0x218f], [0x2190, 0x21ff], [0x2200, 0x22ff],
  [0x2460, 0x24ff], [0x25a0, 0x25ff], [0x2600, 0x26ff], [0x2700, 0x27bf], [0x3000, 0x303f], [0x3131, 0x318e], [0xff01, 0xff5e],
];
const inRange = (cp) => RANGES.some(([a, b]) => cp >= a && cp <= b);

function faceMetrics(path) {
  const font = opentype.parse(readFileSync(path).buffer);
  const glyphs = {};
  for (let i = 0; i < font.glyphs.length; i++) {
    const g = font.glyphs.get(i);
    for (const cp of g.unicodes ?? []) if (inRange(cp)) glyphs[cp] = g.advanceWidth;
  }
  const hangul = new Map();
  for (let cp = 0xac00; cp <= 0xd7a3; cp++) {
    const g = font.charToGlyph(String.fromCodePoint(cp));
    if (g?.index) hangul.set(g.advanceWidth, (hangul.get(g.advanceWidth) ?? 0) + 1);
  }
  const [[hangulWidth]] = [...hangul.entries()].sort((a, b) => b[1] - a[1]);
  if (hangul.size > 1) console.warn(`${path}: Hangul widths not uniform ${JSON.stringify([...hangul])} — using the most common`);
  return {
    unitsPerEm: font.unitsPerEm,
    ascender: font.ascender,
    descender: font.descender,
    hangul: hangulWidth,
    glyphs,
  };
}

const out = {};
for (const [family, weights] of Object.entries(FACES)) {
  out[family] = {};
  for (const [weight, path] of Object.entries(weights)) out[family][weight] = faceMetrics(path);
}
const dest = new URL("../src/metrics.js", import.meta.url);
const body = `// Generated by tools/gen-metrics.mjs — do not edit.\n// Advance widths (font units) for Pretendard (body) and Galmuri11 (display), SIL OFL 1.1.\nexport default ${JSON.stringify(out)};\n`;
writeFileSync(dest, body);
console.log(`wrote ${dest.pathname} (${(body.length / 1024).toFixed(1)} KB)`);
